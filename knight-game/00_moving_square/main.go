// package main — это точка входа. Каждая программа на Go начинается с main.
package main

import (
    // Стандартная библиотека Go: работа с цветами (RGBA)
    "image/color"
    // Стандартная библиотека Go: логирование ошибок (вывод в консоль и завершение программы)
    "log"

    // Ядро Ebitengine: игровой цикл, окно, ввод, графика
    "github.com/hajimehoshi/ebiten/v2"
    // Утилиты Ebitengine: упрощённые функции для отладки.
    // DrawRect — рисование прямоугольников, DrawCircle — кругов, DebugPrint — вывод текста.
    "github.com/hajimehoshi/ebiten/v2/ebitenutil"
)

// Game — наша главная структура, "мировая модель".
// Она хранит всё состояние игры: игрока, врагов, предметы, настройки уровня.
// Ebitengine требует от нас, чтобы эта структура имела методы Update, Draw, Layout.
type Game struct {
    // Координаты игрока. float64 для плавного движения.
    // В языке Go строчные буквы означают, что поле приватное (доступно только внутри пакета main).
    playerX, playerY float64
}

// Update — игровая логика. Вызывается каждый кадр ПЕРЕД отрисовкой.
// Здесь мы обрабатываем ввод, двигаем объекты, считаем физику, проверяем правила игры.
func (g *Game) Update() error {
    // Скорость движения в пикселях за кадр.
    // При 60 FPS это 4*60 = 240 пикселей в секунду.
    speed := 4.0

    // ebiten.IsKeyPressed проверяет, ЗАЖАТА ли клавиша прямо сейчас.
    // Это не событие "нажали", а непрерывное состояние.
    // Поддерживаем и WASD (левая рука), и стрелки (правая рука).

    // W или Стрелка Вверх → двигаемся вверх (Y уменьшается, потому что ноль вверху экрана)
    if ebiten.IsKeyPressed(ebiten.KeyW) || ebiten.IsKeyPressed(ebiten.KeyArrowUp) {
        g.playerY -= speed
    }
    // S или Стрелка Вниз → двигаемся вниз (Y увеличивается)
    if ebiten.IsKeyPressed(ebiten.KeyS) || ebiten.IsKeyPressed(ebiten.KeyArrowDown) {
        g.playerY += speed
    }
    // A или Стрелка Влево → двигаемся влево (X уменьшается)
    if ebiten.IsKeyPressed(ebiten.KeyA) || ebiten.IsKeyPressed(ebiten.KeyArrowLeft) {
        g.playerX -= speed
    }
    // D или Стрелка Вправо → двигаемся вправо (X увеличивается)
    if ebiten.IsKeyPressed(ebiten.KeyD) || ebiten.IsKeyPressed(ebiten.KeyArrowRight) {
        g.playerX += speed
    }

    // Если Update вернёт ошибку, игра аварийно завершится.
    // Пока ошибок нет — возвращаем nil (отсутствие ошибки).
    return nil
}

// Draw — отрисовка кадра. Вызывается ПОСЛЕ Update.
// Получает screen — это холст, который будет показан на экране.
// ВСЁ, что мы хотим увидеть, мы должны нарисовать на screen.
func (g *Game) Draw(screen *ebiten.Image) {
    // Fill заливает ВЕСЬ screen указанным цветом, очищая предыдущий кадр.
    // RGBA: R=20 (красный), G=20 (зелёный), B=30 (синий), A=255 (полностью непрозрачный).
    // Получается очень тёмный сине-серый.
    screen.Fill(color.RGBA{20, 20, 30, 255})

    // Задаём размеры прямоугольника игрока: 32 пикселя в ширину и высоту.
    playerW, playerH := 32.0, 32.0

    // ebitenutil.DrawRect рисует залитый прямоугольник.
    // Аргументы: холст, X, Y, Ширина, Высота, Цвет.
    // Цвет: RGBA{220, 60, 60, 255} — насыщенный красный, непрозрачный.
    // Координаты берутся из модели (g.playerX, g.playerY), которую обновил Update.
    ebitenutil.DrawRect(screen, g.playerX, g.playerY, playerW, playerH, color.RGBA{220, 60, 60, 255})
}

// Layout согласует размеры: физическое окно ОС и логический размер нашей игры.
// Вызывается, когда окно создаётся или меняет размер (пользователь потянул за угол).
//
// outsideWidth, outsideHeight — реальный размер окна в пикселях на экране.
//
// Возвращаемые значения — "логический" размер игры.
// Мы говорим: "Наша игра живёт в разрешении 640x480".
// Если окно больше — Ebitengine сам растянет картинку, сохраняя пропорции.
func (g *Game) Layout(outsideWidth, outsideHeight int) (int, int) {
    // Всегда возвращаем фиксированное логическое разрешение.
    return 640, 480
}

// main — точка входа в программу. Выполняется один раз при запуске.
func main() {
    // Создаём экземпляр нашей игры — "нью-гейм".
    // Указан начальные координаты: игрок появится примерно в центре экрана (300, 220).
    game := &Game{
        playerX: 300,
        playerY: 220,
    }

    // Задаём начальный размер окна в физических пикселях.
    // Совпадает с логическим разрешением из Layout, чтобы картинка была 1:1 без масштабирования.
    ebiten.SetWindowSize(640, 480)
    // Заголовок окна (вкладка в панели задач, шапка окна).
    ebiten.SetWindowTitle("Knight Game Prototype")

    // ebiten.RunGame запускает главный игровой цикл.
    // Эта функция БЛОКИРУЕТ выполнение и вернёт ошибку, только если игра завершится с ошибкой.
    // Если игрок закроет окно — RunGame вернёт nil (штатное завершение) и мы выйдем без ошибки.
    if err := ebiten.RunGame(game); err != nil {
        // log.Fatal выводит ошибку в консоль и завершает программу с ненулевым кодом.
        log.Fatal(err)
    }
}

